"""v0.200: Planejamento anual de outro ano. Ano do planejamento no topo (ano passado até dois à frente, com ✓ onde há meta), convite para
planejar o ano seguinte a partir de outubro, "Começar com as premissas de 2026" no ano novo, receita dos últimos 12 meses quando o ano
anterior ainda não fechou, e Excluir a meta. Banco fa (Escola Aurora). Apaga o que criou."""
import sys, os, json, subprocess; sys.path.insert(0, '.')
import front
from playwright.sync_api import sync_playwright
WS = 'ac56e719-7325-4062-aa47-74bc2141f89d'
SHOT = '/tmp/claude-0/-home-claude/6d4aa2ee-cf0f-5c9b-bd48-3047ac34b6ff/scratchpad/shots200/'; os.makedirs(SHOT, exist_ok=True)
def sql(q):
    r = subprocess.run(['psql', '-h', '/var/run/postgresql', '-p', '55432', '-U', 'postgres', '-d', 'fa', '-Atq', '-v', 'ON_ERROR_STOP=1', '-c', q], capture_output=True, text=True)
    if r.returncode: raise Exception(r.stderr.strip())
    return r.stdout.strip()
falhas = []
def chk(c, msg):
    print(('ok   ' if c else 'FALHA ') + msg)
    if not c: falhas.append(msg)
def limpa(): sql(f"delete from plano_anual where workspace_id = '{WS}'")
limpa()
sql(f"""insert into plano_anual (workspace_id, ano, caminho, modo_ambicao, premissas, pct_pessimista, pct_otimista, base_de, cenario_meta, meta_receita)
  values ('{WS}', 2026, 'ambicao', 'lucro', '{{"custos_fixos":{{"valor":300000,"fonte":"digitado"}},"custos_variaveis":{{"valor":12,"fonte":"digitado"}},"lucro_desejado":{{"valor":150000,"fonte":"digitado"}},"_imposto":{{"regime":"simples_auto","folha":120000}}}}', 15, 25, 'ambicao', 'base', 600000)""")
with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx, pg = front.abre(b, hoje='2026-11-01', vw=1440, vh=1000)
    front.vai(pg, 'mkt-camp', "S.tabMkt = 'plan'; S.ano = 2026; S.campSel = null;", 6000)
    t = pg.inner_text('#paAnos')
    chk(all(str(x) in t for x in (2025, 2026, 2027, 2028)) and 'Ano do planejamento' in t, 'ano do planejamento no topo, de 2025 a 2028: ' + t.replace('\n', ' ')[:120])
    chk('✓ meta' in pg.inner_text('#paAnos [data-pano="2026"]') and '✓' not in pg.inner_text('#paAnos button[data-pano="2027"]'), 'o ano com meta tem ✓')
    chk('planeje 2027' in t, 'em novembro, convida a planejar 2027')
    chk(pg.locator('#paDel').count() == 1, 'a meta salva tem Excluir a meta')
    pg.screenshot(path=SHOT + '1_2026.png')
    pg.click('#paAnos button[data-pano="2027"]'); pg.wait_for_timeout(4000)
    t = pg.inner_text('#paAno')
    chk('Ainda não há meta para 2027' in t and pg.locator('#paCopia').count() == 1 and 'premissas de 2026' in t, '2027 vazio oferece começar com as premissas de 2026')
    chk(pg.input_value('#anoSel') == '2027', 'as metas mês a mês acompanham o ano escolhido')
    pg.screenshot(path=SHOT + '2_2027_vazio.png')
    pg.click('#paCopia'); pg.wait_for_timeout(1200)
    chk('2027' in pg.inner_text('#modalRoot h2') and pg.is_checked('#modalRoot [name=caminho][value=ambicao]'), 'abre o passo a passo de 2027 com o caminho de 2026')
    pg.click('#modalRoot [data-pn="1"]'); pg.wait_for_timeout(250)
    v = pg.input_value('#modalRoot .pa-pr[data-pk="lucro_desejado"] [data-v]'); chk(v in ('150000', 'R$ 150.000,00'), 'as premissas digitadas de 2026 vêm junto (' + v + ')')
    src = pg.locator('#modalRoot .pa-pr[data-pk="receita_anterior"] .pa-src').text_content()
    chk('últimos 12 meses fechados' in src and '2026 ainda não fechou' in src, 'receita do ano anterior: com 2026 aberto, usa os últimos 12 meses fechados')
    pg.click('#modalRoot [data-ps="3"]'); pg.wait_for_timeout(250)
    v = pg.input_value('#modalRoot [name=folha]'); chk(v in ('120000', 'R$ 120.000,00'), 'o imposto de 2026 vem junto (' + v + ')')
    pg.click('#modalRoot [data-ps="4"]'); pg.wait_for_timeout(250)
    chk(pg.input_value('#modalRoot [name=pct_otimista]') == '25', 'os cenários de 2026 vêm junto')
    pg.click('#modalRoot button.pri[type=submit]'); pg.wait_for_timeout(3500)
    r = json.loads(sql(f"select row_to_json(p)::text from plano_anual p where workspace_id = '{WS}' and ano = 2027"))
    chk(r['meta_receita'] is not None and r['premissas']['lucro_desejado']['valor'] == 150000, '2027 gravado com meta própria (%s)' % r['meta_receita'])
    chk(sql(f"select meta_receita from plano_anual where workspace_id = '{WS}' and ano = 2026") in ('600000', '600000.00'), '2026 continua como estava')
    chk('✓ meta' in pg.inner_text('#paAnos [data-pano="2027"]'), '2027 ganha o ✓')
    chk(pg.locator('.pa-tri.on').count() == 0 and 'ainda não começou' in pg.inner_text('#paTri'), '2027: nenhum trimestre em curso, todos por começar')
    pg.screenshot(path=SHOT + '3_2027.png', full_page=True)
    pg.click('#paDel'); pg.wait_for_timeout(500)
    chk('As metas mês a mês' in pg.inner_text('#modalRoot'), 'Excluir avisa que as metas mês a mês não mudam')
    pg.click('#modalRoot button.pri'); pg.wait_for_timeout(3000)
    chk(sql(f"select count(*) from plano_anual where workspace_id = '{WS}' and ano = 2027") == '0' and 'Ainda não há meta para 2027' in pg.inner_text('#paAno'), 'Excluir apaga só a meta de 2027')
    chk(not pg.errs, 'sem erro de JavaScript ' + str(pg.errs[:2]))
    b.close()
limpa()
print('\n%d falha(s)' % len(falhas)); sys.exit(1 if falhas else 0)
